/* Metadata search: index loads only when someone searches. */
(() => {
  'use strict';
  const PAGE_SIZE = 12;
  const normalize = value => String(value || '').normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
  function prepare(posts) {
    return posts.map(post => ({ ...post, fields: [post.title, (post.tags || []).join(' '), (post.categories || []).join(' '), post.description].map(normalize) }));
  }
  function search(posts, query) {
    const terms = normalize(query).trim().split(/\s+/).filter(Boolean);
    if (!terms.length) return posts;
    return posts.map((post, order) => {
      let score = 0;
      for (const term of terms) {
        let best = 0;
        post.fields.forEach((field, i) => { if (field.includes(term)) best = Math.max(best, [8, 5, 3, 1][i]); });
        if (!best) return null;
        score += best;
      }
      return { post, score, order };
    }).filter(Boolean).sort((a, b) => b.score - a.score || a.order - b.order).map(result => result.post);
  }
  function paginate(posts, requested) {
    const pages = Math.max(1, Math.ceil(posts.length / PAGE_SIZE));
    const page = Math.min(pages, Math.max(1, Math.floor(Number(requested) || 1)));
    return { items: posts.slice((page - 1) * PAGE_SIZE, page * PAGE_SIZE), page, pages, start: (page - 1) * PAGE_SIZE };
  }
  if (typeof module !== 'undefined' && module.exports) module.exports = { prepare, search, paginate };
  if (typeof document === 'undefined') return;
  const form = document.querySelector('#blog-search');
  if (!form) return;
  const input = form.querySelector('input');
  const clear = form.querySelector('[data-clear]');
  const status = document.querySelector('#search-status');
  const archive = document.querySelector('#archive-list');
  const results = document.querySelector('#search-results');
  const pager = document.querySelector('#search-pagination');
  const previous = pager.querySelector('[data-previous]');
  const next = pager.querySelector('[data-next]');
  const pageLabel = pager.querySelector('span');
  let indexPromise, revision = 0, timer, currentPage = 1, currentQuery = '';

  function loadIndex() {
    if (!indexPromise) indexPromise = fetch(form.dataset.index).then(response => {
      if (!response.ok) throw new Error('Search unavailable');
      return response.json();
    }).then(prepare).catch(error => { indexPromise = undefined; throw error; });
    return indexPromise;
  }
  function element(tag, className, text) {
    const node = document.createElement(tag);
    node.className = className;
    if (text !== undefined) node.textContent = text;
    return node;
  }
  function renderPost(post, number) {
    const link = element('a', 'journal-entry');
    // Only same-site paths generated by Jekyll are navigable.
    if (typeof post.url !== 'string' || !post.url.startsWith('/') || post.url.startsWith('//')) return document.createDocumentFragment();
    link.href = post.url;
    const date = element('div', 'entry-date');
    const time = element('time', '', post.displayDate);
    time.dateTime = post.date;
    date.append(time, element('span', '', String(number).padStart(2, '0')));
    const copy = element('div', 'entry-copy');
    copy.append(element('p', 'entry-category', post.categories.join(' / ')), element('h3', '', post.title));
    if (post.description) copy.append(element('p', '', post.description));
    let thumbnail;
    if (typeof post.image === 'string' && post.image.startsWith('/') && !post.image.startsWith('//')) {
      thumbnail = element('span', 'entry-image');
      thumbnail.setAttribute('aria-hidden', 'true');
      const image = document.createElement('img');
      image.src = post.image; image.alt = ''; image.width = 420; image.height = 264; image.loading = 'lazy';
      thumbnail.append(image);
    }
    const arrow = element('span', 'entry-arrow', '↗');
    arrow.setAttribute('aria-hidden', 'true');
    link.append(date, copy);
    if (thumbnail) link.append(thumbnail);
    link.append(arrow);
    return link;
  }
  function updateURL(query, page) {
    const url = new URL(location.href);
    if (query) url.searchParams.set('q', query); else url.searchParams.delete('q');
    if (query && page > 1) url.searchParams.set('page', page); else url.searchParams.delete('page');
    history.replaceState(null, '', url);
  }
  async function run(requestedPage = 1, writeURL = true) {
    const token = ++revision;
    const query = input.value.trim();
    currentQuery = query;
    clear.hidden = !input.value;
    if (writeURL) updateURL(query, requestedPage);
    if (!query) {
      archive.hidden = false; results.hidden = true; pager.hidden = true;
      results.replaceChildren(); results.removeAttribute('aria-busy'); status.textContent = '';
      return;
    }
    archive.hidden = true; results.hidden = false; pager.hidden = true;
    results.replaceChildren(); results.setAttribute('aria-busy', 'true');
    status.textContent = 'Searching the journal…';
    try {
      const posts = await loadIndex();
      if (token !== revision) return;
      const matches = search(posts, query);
      const selection = paginate(matches, requestedPage);
      currentPage = selection.page;
      if (writeURL) updateURL(query, currentPage);
      const fragment = document.createDocumentFragment();
      selection.items.forEach((post, i) => fragment.append(renderPost(post, selection.start + i + 1)));
      if (!matches.length) fragment.append(element('p', 'search-empty', 'No entries found. Try another title, topic, or keyword.'));
      results.replaceChildren(fragment);
      status.textContent = matches.length ? `${matches.length} ${matches.length === 1 ? 'entry' : 'entries'} for “${query}” · Showing ${selection.start + 1}–${selection.start + selection.items.length}` : `No entries for “${query}”`;
      pager.hidden = selection.pages <= 1;
      previous.disabled = selection.page === 1; next.disabled = selection.page === selection.pages;
      pageLabel.textContent = `Page ${selection.page} of ${selection.pages}`;
    } catch {
      if (token !== revision) return;
      archive.hidden = false; results.hidden = true;
      status.textContent = 'Search could not load. You can still browse below. Press Enter to retry.';
    } finally {
      if (token === revision) results.removeAttribute('aria-busy');
    }
  }
  input.addEventListener('input', () => {
    clearTimeout(timer);
    ++revision; // Ignore an older request even during this debounce window.
    clear.hidden = !input.value;
    timer = setTimeout(() => run(), 160);
  });
  form.addEventListener('submit', event => { event.preventDefault(); clearTimeout(timer); run(); });
  clear.addEventListener('click', () => { clearTimeout(timer); input.value = ''; run(); input.focus(); });
  input.addEventListener('keydown', event => { if (event.key === 'Escape') { event.preventDefault(); clear.click(); } });
  previous.addEventListener('click', () => changePage(-1));
  next.addEventListener('click', () => changePage(1));
  function changePage(delta) {
    clearTimeout(timer);
    run(input.value.trim() === currentQuery ? currentPage + delta : 1).then(() => {
      results.focus({ preventScroll: true });
      form.scrollIntoView({ block: 'start', behavior: 'auto' });
    });
  }
  function fromURL() {
    clearTimeout(timer);
    const params = new URLSearchParams(location.search);
    input.value = (params.get('q') || '').slice(0, 200);
    run(params.get('page') || 1, false);
  }
  window.addEventListener('popstate', fromURL);
  form.hidden = false;
  fromURL();
})();
